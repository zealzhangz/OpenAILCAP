"""TRUSTED B4 sandbox worker: executes one already policy-checked source.

Run ONLY inside Docker --network none --read-only --cap-drop ALL. This script
is never generated by a model. Business oracle is independent of the model.
"""
import hashlib
import itertools
import json
from pathlib import Path


def expected(amount,supplier,months):
    a = (amount>100000000)*20 + (amount>500000000)*15
    b = 35 if supplier<=29 else (20 if supplier<=59 else 0)
    c = 25 if months<=5 else (10 if months<=23 else 0)
    value=a+b+c
    if amount>200000000 and supplier<45 and value<90:
        value=90
    return 100 if value>100 else value


def main():
    src=Path("/workspace/rule.py").read_text(encoding="utf-8")
    code=compile(src,"/workspace/rule.py","exec")
    env={"__builtins__":{"min":min,"max":max}}
    exec(code,env)
    func=env["score_contract"]
    cases=itertools.product(
        (0,1,100000000,100000001,200000000,200000001,500000000,
         500000001,10**12),
        (0,29,30,44,45,59,60,100),
        (0,5,6,23,24,240)
    )
    total=0
    for amount,supplier,months in cases:
        actual=func(amount,supplier,months)
        expected_result=expected(amount,supplier,months)
        if type(actual) is not int or actual!=expected_result:
            print(json.dumps({"status":"FAIL","error":"BUSINESS_ORACLE_MISMATCH",
                              "caseIndex":total,"actual":actual,
                              "expected":expected_result}))
            return 3
        total+=1
    result=None
    payload_path=Path("/workspace/payload.json")
    if payload_path.exists():
        req=json.loads(payload_path.read_text(encoding="utf-8"))
        if (not isinstance(req,dict) or set(req)!={"amount_minor","supplier_score",
                                                    "months_active"}):
            print(json.dumps({"status":"FAIL","error":"RUNTIME_INPUT_SHAPE"}))
            return 4
        amount=req["amount_minor"];supplier=req["supplier_score"];months=req["months_active"]
        if any(type(v) is not int for v in (amount,supplier,months)) or (
            not 0<=amount<=10**12 or not 0<=supplier<=100 or not 0<=months<=240
        ):
            print(json.dumps({"status":"FAIL","error":"RUNTIME_INPUT_RANGE"}))
            return 5
        value=func(amount,supplier,months)
        if type(value) is not int or not 0<=value<=100:
            print(json.dumps({"status":"FAIL","error":"RUNTIME_OUTPUT_TYPE"}))
            return 6
        result=value
    print(json.dumps({"status":"PASS","passed":total,"cases":total,
                      "sourceHash":hashlib.sha256(src.encode()).hexdigest(),
                      "result":result},sort_keys=True))
    return 0

if __name__=="__main__":
    try:exit(main())
    except BaseException:
        print(json.dumps({"status":"FAIL","error":"SANDBOX_RUNTIME_EXCEPTION"}))
        raise SystemExit(7)
