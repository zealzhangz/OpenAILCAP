class Failed(AssertionError):
    pass


def expect(observed,**must):
    if not isinstance(observed,dict):
        raise Failed("OBSERVED_NOT_DICTIONARY")
    for key,value in must.items():
        if observed.get(key)!=value:
            raise Failed("FIELD_"+key+"_"+str(observed.get(key)))


def evaluate(case,entries):
    o=[e["observed"] for e in entries]
    if case=="W03":
        expect(o[0],realBrowserHTTP=200,staleAgentHTTP=409,
               humanTitleRetained=True)
    elif case=="W04":
        expect(o[0],agentHTTP=200,staleHumanHTTP=409,
               agentTitleRetained=True)
    elif case=="W05":
        expect(o[0],staleAgent=409,reviewedRebase=200,
               humanTitleRetained=True,agentColumnsRetained=True)
    elif case=="W06":
        expect(o[0],agentHTTP=200,pluginHTTP=409,oneWinner=True)
        expect(o[1],receiptDelta=1,publishedVersion=1,appBUnchanged=True)
        expect(o[2],DockerHTTP=409,AgentHTTP=200,
               physicalWinner="P0A-Agent-Race-Title",oneSQLReceipt=True)
    elif case=="W07":
        expect(o[0],dockerUid=65534,hostSqliteRw="DENIED",
               toolHTTP=200,physicalNoChange=True)
        expect(o[1],DockerHTTP=409,AgentHTTP=200,oneSQLReceipt=True)
    elif case=="W08":
        expect(o[0],replayHTTP=200,noAdditionalReceipt=True,
               nativeStillPublishedV1=True)
        expect(o[1],sameAgentReplay=200,physicalUnchanged=True)
    elif case=="W09":
        expect(o[0],otherActorReplay=409,alteredDigestReplay=409,
               physicalUnchanged=True)
        expect(o[1],oldChangeIdReplay=200,otherActor=409,
               forgedDigest=409,physicalUnchanged=True)
    elif case=="W12":
        if (not isinstance(o[0].get("baselineHash"),str) or
            not re.fullmatch(r"[0-9a-f]{64}",o[0]["baselineHash"]) or
            not isinstance(o[0].get("approvedHash"),str) or
            not re.fullmatch(r"[0-9a-f]{64}",o[0]["approvedHash"]) or
            o[0]["baselineHash"]==o[0]["approvedHash"] or
            len(o[0].get("changedJsonPaths",[]))<3):
            raise Failed("FULL_PACK_DIFF_NOT_DEMONSTRATED")
        expect(o[1],decision="REJECTED_UNTRUSTED_PACK",
               executedNativeCommands=0)
        for path in ("/customUnsafeDomain","/plugins/0","/roles/0",
                     "/tables/1","/triggers/0"):
            if path not in o[1]["dangerousDiffPaths"]:
                raise Failed("UNRELATED_PACK_PATH_NOT_REVIEWED_"+path)
        expect(o[2],noApproval="DENIED",realDockerPlugin=403,
               agent=403,noNativeCliRun=True)
        expect(o[3],missingPrivilege="DENIED",pluginApprover="DENIED",
               forgedSignature="DENIED",modifiedPackAfterApproval="DENIED",
               nativeCliRun=False)
        expect(o[4],actualSaltcornCli=[0],activeNativeUntouched=True,
               sourceVersion=3,approvedOneShot=True)
        expect(o[5],approvedReplay="DENIED",failedInstallToken="CONSUMED",
               liveNativeNoChange=True,physicalAuthorityNoChange=True)
    elif case=="W16":
        expect(o[0],authorityConfigRead="DENIED",authorityRead="DENIED",
               authoritySQLWrite="DENIED",authorityWrite="DENIED")
        if not re.fullmatch(r"sha256:[0-9a-f]{64}",
                            o[1].get("imageId","")):
            raise Failed("DOCKER_NOT_PINNED_REAL_IMAGE")
        expect(o[1],noNetwork=True,readOnly=True,
               noHostDatabaseMount=True,noSecretInDockerArgv=True)
        expect(o[2],dockerUid=65534,dockerSocket="DENIED",
               hostSqliteRw="DENIED",hostSqliteRead="DENIED",
               hostSecretRead="DENIED",outboundTcp="DENIED",
               physicalNoChange=True)
        expect(o[3],unauthorizedSqlReceiptDelta=0)
        if o[3].get("status")!={
            "publish":403,"code":403,"sql":403,"model":403}:
            raise Failed("PLUGIN_UNDECLARED_TOOL_WROTE")
    elif case=="W22":
        expect(o[0],sessionAuthenticated=True)
        expect(o[1],realChromiumHTTP=200,modelCalls=0,
               independentSQLReadback=True)
    else:
        raise Failed("UNREGISTERED_CASE_"+case)
    return {"status":"PASS","test_id":case,"checks":CHECKS[case],
            "physical_and_browser_oracles_cross_checked":True}


def judge(document):
    if (document.get("modelCalls")!=0 or
        document.get("g1Passed") is not False or
        not isinstance(document.get("checks"),list)):
        raise Failed("ORIGINAL_E2E_CONTEXT_INVALID")
    checks=document["checks"]
    if any(c.get("status")!="PASS" for c in checks):
        raise Failed("ORIGINAL_E2E_HAS_FAILURE")
    selected={}
    for case,ids in CHECKS.items():
        entries=[]
        for name in ids:
            matches=[c for c in checks if c.get("id")==name]
            if len(matches)!=1 or matches[0]["status"]!="PASS":
                raise Failed("MISSING_REAL_CHECK_"+name)
            entries.append(matches[0])
        selected[case]=evaluate(case,entries)
    if len(selected)!=10:
        raise Failed("EXPECTED_EXACTLY_TEN_REVIEWED_CASES")
    return {"status":"PASS","cases":selected,
            "sourceSameInstanceChecks":len(checks),
            "independentFromImplementation":True,
            "G1Passed":False}


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--evidence",required=True)
    p.add_argument("--output",required=True)
    args=p.parse_args()
    result=judge(json.loads(Path(args.evidence).read_text()))
    Path(args.output).write_text(json.dumps(result,indent=2)+"\n")
    print("G1_W_GOVERNANCE_FORMAL|"+json.dumps({
        "status":result["status"],"pass_ids":list(result["cases"]),
        "sourceSameInstanceChecks":result["sourceSameInstanceChecks"],
        "G1Passed":False
    },sort_keys=True))
    return 0


if __name__=="__main__":
    raise SystemExit(main())
